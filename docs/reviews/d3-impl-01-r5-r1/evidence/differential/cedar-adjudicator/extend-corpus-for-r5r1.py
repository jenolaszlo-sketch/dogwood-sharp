#!/usr/bin/env python3
"""Extend the direct Cedar adjudication corpus with the R5-R1 controls.

The R5-R1 corpus adds malformed typed-encoding controls. The base adjudication
corpus already covered the bare-string spelling of a malformed value, but not
the explicit `__extn` spelling or the implicit `{fn,arg}` spelling with an
invalid argument, and it did not cross-reference the R5-R1 fixture ids.

This script appends exactly the missing adjudication cases and adds the
fixture cross-references, so every R5-R1 malformed control has a direct Cedar
authority row. It is idempotent: running it twice leaves the corpus
unchanged, and a case that is already present but differs from the intended
case is an error rather than a silent duplicate.

The outcomes are regenerated by the adjudicator itself; this script never
derives an outcome.
"""

from __future__ import annotations

import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
CORPUS = HERE / "corpus.json"

IPADDR_SCHEMA = (
    "namespace App { entity User; entity Doc; action read appliesTo "
    "{ principal: [User], resource: [Doc], context: { ip: ipaddr } }; }"
)
DATETIME_SCHEMA = (
    "namespace App { entity User; entity Doc; action read appliesTo "
    "{ principal: [User], resource: [Doc], context: { ts: datetime } }; }"
)
DECIMAL_SCHEMA = (
    "namespace App { entity User; entity Doc; action read appliesTo "
    "{ principal: [User], resource: [Doc], context: { price: decimal } }; }"
)

IPADDR_POLICY = (
    'permit(principal, action == App::Action::"read", resource)\n'
    'when { context.ip == ip("192.168.1.1") };'
)
DATETIME_POLICY = (
    'permit(principal, action == App::Action::"read", resource)\n'
    'when { context.ts == datetime("2024-01-01T00:00:00Z") };'
)
DECIMAL_POLICY = (
    'permit(principal, action == App::Action::"read", resource)\n'
    'when { context.price == decimal("1.5") };'
)

# The cross-references the base corpus did not carry.
FIXTURE_REFERENCES = {
    "ADJ-C01": "R5R1-C23-01-ipaddr-invalid-bare-string",
}

ADDITIONAL_CASES = [
    {
        "id": "ADJ-C23",
        "fixtureId": "R5R1-C23-05-ipaddr-invalid-implicit-escape",
        "note": "ipaddr implicit escape with an invalid argument",
        "schema": IPADDR_SCHEMA,
        "policy": IPADDR_POLICY,
        "action": 'App::Action::"read"',
        "principal": 'App::User::"alice"',
        "resource": 'App::Doc::"d1"',
        "context": {"ip": {"fn": "ip", "arg": "not-an-ip"}},
    },
    {
        "id": "ADJ-C24",
        "fixtureId": "R5R1-C23-02-ipaddr-invalid-octet",
        "note": "ipaddr explicit escape with an out-of-range octet",
        "schema": IPADDR_SCHEMA,
        "policy": IPADDR_POLICY,
        "action": 'App::Action::"read"',
        "principal": 'App::User::"alice"',
        "resource": 'App::Doc::"d1"',
        "context": {"ip": {"__extn": {"fn": "ip", "arg": "999.1.1.1"}}},
    },
    {
        "id": "ADJ-C25",
        "fixtureId": "R5R1-C23-03-datetime-invalid-escape",
        "note": "datetime explicit escape with an unparsable argument",
        "schema": DATETIME_SCHEMA,
        "policy": DATETIME_POLICY,
        "action": 'App::Action::"read"',
        "principal": 'App::User::"alice"',
        "resource": 'App::Doc::"d1"',
        "context": {"ts": {"__extn": {"fn": "datetime", "arg": "not-a-date"}}},
    },
    {
        "id": "ADJ-C26",
        "fixtureId": "R5R1-C23-04-decimal-invalid-escape",
        "note": "decimal explicit escape with a non-numeric argument",
        "schema": DECIMAL_SCHEMA,
        "policy": DECIMAL_POLICY,
        "action": 'App::Action::"read"',
        "principal": 'App::User::"alice"',
        "resource": 'App::Doc::"d1"',
        "context": {"price": {"__extn": {"fn": "decimal", "arg": "not-a-number"}}},
    },
]


def main() -> int:
    corpus = json.loads(CORPUS.read_text(encoding="utf-8"))
    existing = {case["id"] for case in corpus["cases"]}

    for case_id, fixture_id in FIXTURE_REFERENCES.items():
        if case_id not in existing:
            raise SystemExit(f"the base corpus no longer carries `{case_id}`")
        for case in corpus["cases"]:
            if case["id"] == case_id:
                if case.get("fixtureId") not in (None, fixture_id):
                    raise SystemExit(f"`{case_id}` already carries a fixture reference")
                case["fixtureId"] = fixture_id

    for case in ADDITIONAL_CASES:
        existing_case = next(
            (row for row in corpus["cases"] if row["id"] == case["id"]), None
        )
        if existing_case is None:
            corpus["cases"].append(case)
        elif existing_case != case:
            raise SystemExit(
                f"`{case['id']}` is already present with different content; "
                f"refusing to overwrite it"
            )
        existing.add(case["id"])

    corpus["comment"] = (
        "DOGWOOD-SHARP-D3-IMPL-01-R5-R1 direct Cedar adjudication corpus. "
        "Independently constructed minimal Cedar policies and schema-directed "
        "JSON requests. Group A reproduces the 18 R5 baseline replay cases "
        "(fixture cross-referenced). Group B covers adjacent valid "
        "representations. Group C covers invalid and malformed "
        "representations that must not acquire validity, including the "
        "R5-R1 malformed typed-encoding controls."
    )

    CORPUS.write_text(
        json.dumps(corpus, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(f"cases: {len(corpus['cases'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
