# DOGWOOD-SHARP-D3-IMPL-01-R5-R1 corrected-reference dependency preparation.
#
# Stages the corrected oracle build tree into a work root outside this
# repository and applies the exact committed typed-context patch to the local
# pinned upstream Dogwood checkout. Everything is verified before anything
# links against it:
#
#   1. The source checkout must resolve to exactly the pinned upstream
#      revision 929f49e7305534ac61ef06cf8e47269c596dc851 (dogwood 1.1.2),
#      the same revision the R4 oracle's committed Cargo.lock pins.
#   2. The patch must apply with git apply under core.autocrlf=false /
#      core.eol=lf so the generated bytes are reproducible on any host. The
#      work root must be outside this repository: the repository's
#      .gitattributes (text=auto eol=lf) would otherwise reinterpret the
#      vendored upstream bytes during apply.
#   3. The patched dogwood-language/src/api.rs must hash to the recorded
#      value, and the patched tree must differ from the pinned tree in that
#      one file only.
#
# The staged tree is build scratch, exactly like the compiled binaries: it is
# reproducible from the committed inputs and is not part of the evidence
# manifest.
#
# Usage: pwsh -File prepare-dogwood.ps1 -WorkRoot <directory>

param(
    [Parameter(Mandatory = $true)]
    [string] $WorkRoot
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$pinnedRevision = '929f49e7305534ac61ef06cf8e47269c596dc851'
$expectedPatchedApiSha256 = '4ff2eb118a08c13eddf1d54ea1cf178db70f1a148bacb6e377333abeb5b67dd3'
$here = $PSScriptRoot
$patchPath = Join-Path $here 'dogwood-typed-context.patch'

if (-not (Test-Path $WorkRoot)) {
    New-Item -ItemType Directory -Force -Path $WorkRoot | Out-Null
}
$workRootPath = (Resolve-Path $WorkRoot).Path
$staging = Join-Path $workRootPath 'corrected-oracle'
$patchedRoot = Join-Path $workRootPath 'dogwood-patched'

if ($workRootPath.StartsWith((Resolve-Path (Join-Path $here '../../../..')).Path)) {
    throw 'the work root must be outside this repository so .gitattributes cannot reinterpret the vendored bytes'
}

function Find-PinnedCheckout {
    $checkoutRoots = Get-ChildItem (Join-Path $env:USERPROFILE '.cargo/git/checkouts') -Directory -Filter 'dogwood-*' -ErrorAction SilentlyContinue
    foreach ($root in $checkoutRoots) {
        foreach ($candidate in Get-ChildItem $root.FullName -Directory) {
            $revision = (& git -C $candidate.FullName rev-parse HEAD 2>$null)
            if ($LASTEXITCODE -eq 0 -and $revision -eq $pinnedRevision) {
                return $candidate.FullName
            }
        }
    }
    throw "no local cargo checkout resolves to the pinned Dogwood revision $pinnedRevision; fetch it once with cargo (offline reuse only)"
}

if (-not (Test-Path $patchPath)) {
    throw "the committed patch is missing: $patchPath"
}
if (-not (Test-Path (Join-Path $here 'Cargo.toml.template'))) {
    throw 'the committed manifest template is missing'
}
if (-not (Test-Path (Join-Path $here 'src/main.rs'))) {
    throw 'the committed oracle source is missing'
}

$source = Find-PinnedCheckout
Write-Output "pinned checkout: $source"

foreach ($directory in @($staging, $patchedRoot)) {
    if (Test-Path $directory) {
        Remove-Item $directory -Recurse -Force
    }
    New-Item -ItemType Directory -Force -Path $directory | Out-Null
}

# Copy the pinned tree byte-for-byte (no target/ scratch, no VCS metadata).
robocopy $source $patchedRoot /E /NFL /NDL /NJH /NJS /NP /XD target .git | Out-Null
if ($LASTEXITCODE -ge 8) {
    throw "the pinned Dogwood tree could not be copied (robocopy exit $LASTEXITCODE)"
}

& git -C $patchedRoot -c core.autocrlf=false -c core.eol=lf apply -p1 --whitespace=nowarn $patchPath
if ($LASTEXITCODE -ne 0) {
    throw "the typed-context patch did not apply to the pinned tree"
}

$apiPath = Join-Path $patchedRoot 'dogwood-language/src/api.rs'
$actual = (Get-FileHash $apiPath -Algorithm SHA256).Hash.ToLowerInvariant()
if ($actual -ne $expectedPatchedApiSha256) {
    throw "patched api.rs hash $actual does not match the recorded $expectedPatchedApiSha256"
}

# Exactly one file may differ from the pinned tree.
$sourceFiles = Get-ChildItem $source -Recurse -File | Where-Object { $_.FullName -notmatch '\\target\\|\\.git' }
$different = New-Object System.Collections.Generic.List[string]
foreach ($file in $sourceFiles) {
    $relative = $file.FullName.Substring($source.Length + 1) -replace '\\', '/'
    $patched = Join-Path $patchedRoot $relative
    if (-not (Test-Path $patched)) {
        $different.Add("$relative (missing)")
        continue
    }
    $sourceHash = (Get-FileHash $file.FullName -Algorithm SHA256).Hash
    $patchedHash = (Get-FileHash $patched -Algorithm SHA256).Hash
    if ($sourceHash -ne $patchedHash) {
        $different.Add($relative)
    }
}
if ($different.Count -ne 1 -or $different[0] -ne 'dogwood-language/src/api.rs') {
    throw "the patched tree diverges from the pinned tree beyond the single documented file: $($different -join '; ')"
}

# Stage the oracle build tree outside the repository and write the manifest
# with the absolute path of the patched dependency.
Copy-Item (Join-Path $here 'src') $staging -Recurse -Force
if (Test-Path (Join-Path $here 'Cargo.lock')) {
    Copy-Item (Join-Path $here 'Cargo.lock') $staging -Force
}
$manifest = (Get-Content (Join-Path $here 'Cargo.toml.template') -Raw) -replace
    '__DOGWOOD_PATCHED_PATH__', ((Join-Path $patchedRoot 'dogwood-language') -replace '\\', '/')
[IO.File]::WriteAllText((Join-Path $staging 'Cargo.toml'), $manifest, [Text.UTF8Encoding]::new($false))

$provenance = [ordered]@{
    sourceCheckout = $source
    pinnedRevision = $pinnedRevision
    patch = 'dogwood-typed-context.patch'
    patchSha256 = (Get-FileHash $patchPath -Algorithm SHA256).Hash.ToLowerInvariant()
    patchedApiSha256 = $actual
    stagingRoot = $staging
    generatedAtUtc = (Get-Date).ToUniversalTime().ToString('o')
    filesChanged = $different
}
[IO.File]::WriteAllText(
    (Join-Path (Split-Path $staging) 'corrected-oracle-provenance.json'),
    ($provenance | ConvertTo-Json) + [Environment]::NewLine,
    [Text.UTF8Encoding]::new($false))

Write-Output "patched tree verified: exactly dogwood-language/src/api.rs changed; api.rs sha256 $actual"
Write-Output "staged oracle build tree: $staging"
